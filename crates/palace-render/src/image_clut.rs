/// Look up a hotspot-image palette index.
#[must_use]
pub fn image_clut(index: u8) -> u32 {
    IMAGE_CLUT_ARGB[usize::from(index)]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn anchors_match_the_reference_table() {
        assert_eq!(image_clut(0), 0xffff_ffff);
        assert_eq!(image_clut(1), 0xffff_dfff);
        assert_eq!(image_clut(255), 0xff00_0000);
    }

    #[test]
    fn every_entry_is_opaque() {
        assert!(IMAGE_CLUT_ARGB.iter().all(|c| c >> 24 == 0xff));
    }
}
